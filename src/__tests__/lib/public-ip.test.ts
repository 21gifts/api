import { describe, expect, it } from 'vitest';
import { isPublicIp } from '@/lib/public-ip';

describe('isPublicIp', () => {
  it.each([
    '8.8.8.8',
    '93.184.216.34',
    ' 1.1.1.1 ',
    '100.63.255.255',
    '172.32.0.1',
    '192.0.1.1',
    '198.20.0.1',
    '::ffff:8.8.8.8',
    '::ffff:808:808',
    '0:0:0:0:0:ffff:808:808',
    '2002:808:808::1',
    '::ffff:0:808:808',
    '64:ff9b::808:808',
    '2001:4860:4860::8888',
    '2001:2:1::1',
    '2001:30::1',
    '2a00:1450:4001::1',
    '3fff:1000::1',
  ])('accepts %s', (address) => {
    expect(isPublicIp(address)).toBe(true);
  });

  it.each([
    '0.0.0.0',
    '10.0.0.1',
    '127.0.0.1',
    '100.64.0.1',
    '169.254.169.254',
    '172.16.0.1',
    '192.168.1.1',
    '192.0.0.8',
    '192.0.2.1',
    '198.18.0.1',
    '198.51.100.1',
    '203.0.113.1',
    '224.0.0.1',
    '01.2.3.4',
    '256.1.1.1',
    '1.2.3',
    '::',
    '::1',
    '::ffff:127.0.0.1',
    '::ffff:7f00:1',
    '0:0:0:0:0:ffff:7f00:1',
    '2002:7f00:1::',
    '::ffff:0:7f00:1',
    '0:0:0:0:ffff:0:a00:1',
    '64:ff9b::a00:1',
    '64:ff9b:1::1',
    '100::1',
    '5f00::1',
    '3fff::1',
    '2001::1',
    '2001:1::1',
    '2001:db8::1',
    '2001:2:0::1',
    '2001:10::1',
    '2001:20::1',
    'fc00::1',
    'fd12::1',
    'fe80::1',
    'fec0::1',
    'ff02::1',
    'not-an-ip',
    '1::2::3',
    '1:2:3:4:5:6:7:8:9',
    '1:2:3:4:5:6:7',
    'g::1',
    '::g',
    '1:2:3:4::5:6:7:8',
  ])('refuses %s', (address) => {
    expect(isPublicIp(address)).toBe(false);
  });
});
